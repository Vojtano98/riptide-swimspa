// Regenerates src/data/shared/modelBriefs.js from src/data/models/*.js.
// Series pages show per-model specs (hover cards, comparison table) without
// importing every full model file, which would bloat each series page bundle.
// Run: node scripts/gen-model-briefs.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'src/data/models')
const num = (s) => parseFloat(String(s).replace(/\s/g, '').replace(',', '.'))
const out = {}

for (const file of fs.readdirSync(dir).sort()) {
  const mod = await import(path.join(dir, file))
  const m = Object.values(mod)[0]
  const base = [...m.variants].sort((a, b) => a.price - b.price)[0]
  const [len, wid, hei] = base.specs.dimensions.replace(' cm', '').split('×').map((p) => p.trim())
  out[m.slug] = {
    length: num(len),
    width: num(wid),
    height: num(hei),
    volume: num(base.specs.capacity),
    seating: base.specs.seating ?? null,
    massageJets: base.specs.massageJets ?? null,
    swimJets: base.specs.swimJets,
    duo: m.quickSpecs.some((q) => /nezávislé/.test(q.label)),
  }
}

const body = `// GENERATED by scripts/gen-model-briefs.mjs — do not edit by hand.\nexport const modelBriefs = ${JSON.stringify(out, null, 2)}\n`
fs.writeFileSync(path.join(root, 'src/data/shared/modelBriefs.js'), body)
console.log('wrote', Object.keys(out).length, 'briefs')
